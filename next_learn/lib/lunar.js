/* ==================== 1-4. 节日 ==================== */

function nthWeekdayDate(y, month, weekday, n) {
  // y 年 month 月第 n 个 weekday（0 = 周日）
  const first = new Date(y, month - 1, 1);
  const firstW = first.getDay();
  const day = 1 + ((weekday - firstW + 7) % 7) + (n - 1) * 7;
  return new Date(y, month - 1, day);
}

